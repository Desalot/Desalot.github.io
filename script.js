let currentFilter = "all";
let currentAchievement = null;
let lastRandomId = null;
let returnFocus = null;
let returnFocusId = null;
let toastTimer;
let confettiTimer;
let savedPreferences = {};

try {
  const saved = JSON.parse(localStorage.getItem("desalot-legend-archive") || "{}");
  if (saved && typeof saved === "object") savedPreferences = saved;
} catch (_) { /* Private browsing and file:// may restrict storage. */ }
let humbleMode = savedPreferences.humble === true;
const confirmedIds = new Set(Array.isArray(savedPreferences.confirmed) ? savedPreferences.confirmed.filter(id => achievements.some(item => item.id === id)) : []);

function savePreferences() {
  try { localStorage.setItem("desalot-legend-archive", JSON.stringify({ humble: humbleMode, confirmed: Array.from(confirmedIds) })); } catch (_) { /* The archive also works without storage. */ }
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));
}

