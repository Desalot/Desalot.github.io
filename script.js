function syncBelieveButton() {
  const confirmed = currentAchievement && confirmedIds.has(currentAchievement.id);
  believeButton.setAttribute("aria-pressed", String(Boolean(confirmed)));
  believeButton.innerHTML = confirmed ? 'You officially believe <span aria-hidden="true">✓</span>' : 'I believe you <span aria-hidden="true">✳</span>';
}

function populateDialog(item) {
  const image = document.getElementById("dialog-image");
  image.src = item.image;
  image.alt = item.alt;
  image.style.objectPosition = "center 20%";
  document.getElementById("dialog-full-image").href = item.image;
  document.getElementById("dialog-category").textContent = `${item.number} / ${item.categoryLabel.toUpperCase()} / ${humbleMode ? "THE HUMBLE VERSION" : "THE OFFICIAL STORY"}`;
  document.getElementById("dialog-title").textContent = humbleMode ? item.humbleTitle : item.title;
  document.getElementById("dialog-summary").textContent = humbleMode ? item.humbleSummary : item.summary;
  document.getElementById("dossier-meta").innerHTML = `<div><span>LOCATION</span>${escapeHtml(humbleMode ? "Planet Earth, realistically" : item.place)}</div><div><span>DATE</span>${escapeHtml(humbleMode ? "An otherwise normal day" : item.date)}</div><div><span>KEY RESULT</span>${escapeHtml(humbleMode ? "Nothing supernatural" : item.metric)}</div>`;
  document.getElementById("dialog-story").innerHTML = (humbleMode ? item.humbleStory : item.story).map(paragraph => `<p>${escapeHtml(paragraph)}</p>`).join("");
  evidenceContent.innerHTML = `<strong>EXHIBIT ${item.number} — EXTREMELY CIRCUMSTANTIAL</strong>${escapeHtml(item.evidence)}`;
  evidenceContent.hidden = true;
  evidenceButton.setAttribute("aria-expanded", "false");
  syncBelieveButton();
}

function setLegendHash(id) {
  try { history.replaceState(null, "", `${location.pathname}${location.search}${id ? `#legend/${id}` : "#archive"}`); } catch (_) { /* Some local file contexts restrict History. */ }
}

function openAchievement(id, updateHash = true) {
  const item = achievements.find(entry => entry.id === id);
  if (!item) return;
  const wasOpen = dialog.hasAttribute("open");
  if (!wasOpen) {
    returnFocus = document.activeElement;
    returnFocusId = returnFocus && returnFocus.dataset ? returnFocus.dataset.achievement : null;
  }
  currentAchievement = item;
  populateDialog(item);
  if (!wasOpen) {
    document.body.classList.add("modal-open");
    if (typeof dialog.showModal === "function") dialog.showModal();
    else { dialog.setAttribute("open", ""); dialog.classList.add("fallback-open"); dialog.setAttribute("role", "dialog"); dialog.setAttribute("aria-modal", "true"); }
  }
  dialog.scrollTop = 0;
  dialog.querySelector(".dialog-close").focus({ preventScroll: true });
  if (updateHash) setLegendHash(item.id);
}

function afterDialogClosed() {
  document.body.classList.remove("modal-open");
  dialog.classList.remove("fallback-open");
  if (location.hash.startsWith("#legend/")) setLegendHash(null);
  currentAchievement = null;
  if (returnFocus && returnFocus.isConnected) returnFocus.focus({ preventScroll: true });
  else if (returnFocusId && grid.querySelector(`[data-achievement="${returnFocusId}"]`)) grid.querySelector(`[data-achievement="${returnFocusId}"]`).focus({ preventScroll: true });
  else document.getElementById("archive-title").scrollIntoView({ block: "start" });
}

function closeAchievement() {
  if (!dialog.hasAttribute("open")) return;
  if (typeof dialog.close === "function") dialog.close();
  else { dialog.removeAttribute("open"); afterDialogClosed(); }
}

function randomAchievement() {
  const choices = achievements.filter(item => item.id !== lastRandomId);
  const item = choices[Math.floor(Math.random() * choices.length)];
  lastRandomId = item.id;
  openAchievement(item.id);
}

function showToast(message) {
  const toast = document.getElementById("toast");
  clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add("visible");
  toastTimer = setTimeout(() => toast.classList.remove("visible"), 3500);
}

function celebrate() {
  if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const layer = document.getElementById("confetti-layer");
  clearTimeout(confettiTimer);
  layer.replaceChildren();
  const colors = ["#d7f565", "#ff8d58", "#e9e8dc", "#8fb2a0", "#d1b3dc"];
  for (let i = 0; i < 45; i++) {
    const piece = document.createElement("i");
    piece.className = "confetti-piece";
    piece.style.cssText = `--x:${Math.random() * 100}%;--color:${colors[i % colors.length]};--duration:${1.6 + Math.random() * 1.5}s;--delay:${Math.random() * .3}s;--rotation:${Math.random() * 180}deg;--drift:${Math.random() * 160 - 80}px;`;
    layer.appendChild(piece);
  }
  confettiTimer = setTimeout(() => layer.replaceChildren(), 3500);
}

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    try { await navigator.clipboard.writeText(text); return true; } catch (_) { /* Try the older browser path below. */ }
  }
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.cssText = "position:fixed;top:0;left:0;width:1px;height:1px;opacity:0;";
  // Keep it inside the modal so focus remains legal in browsers using dialog inertness.
  (dialog.hasAttribute("open") ? dialog : document.body).appendChild(textarea);
  textarea.select();
  textarea.setSelectionRange(0, text.length);
  let copied = false;
  try { copied = document.execCommand("copy"); } catch (_) { /* Manual copying remains available below. */ }
  textarea.remove();
  document.getElementById("share-button").focus({ preventScroll: true });
  return copied;
}

document.querySelectorAll(".filter").forEach(button => {
  button.addEventListener("click", () => {
    currentFilter = button.dataset.filter;
    document.querySelectorAll(".filter").forEach(filter => {
      const active = filter === button;
      filter.classList.toggle("active", active);
      filter.setAttribute("aria-pressed", String(active));
    });
    renderCards(true);
  });
});

humbleToggle.setAttribute("aria-checked", String(humbleMode));
humbleToggle.addEventListener("click", () => {
  humbleMode = !humbleMode;
  humbleToggle.setAttribute("aria-checked", String(humbleMode));
  savePreferences();
  renderCards(true);
  showToast(humbleMode ? "Humble mode on. Reality has entered the chat." : "Legend mode on. Reality has left the chat.");
});

grid.addEventListener("click", event => {
  const button = event.target.closest("[data-achievement]");
  if (button) openAchievement(button.dataset.achievement);
});
document.querySelectorAll(".random-trigger").forEach(button => button.addEventListener("click", randomAchievement));
dialog.querySelector(".dialog-close").addEventListener("click", closeAchievement);
dialog.addEventListener("close", afterDialogClosed);
// Native dialog contains keyboard focus; provide the same behavior for older browsers.
dialog.addEventListener("keydown", event => {
  if (event.key === "Escape" && typeof dialog.showModal !== "function") { event.preventDefault(); closeAchievement(); }
  if (event.key === "Tab" && typeof dialog.showModal !== "function") {
    const focusable = Array.from(dialog.querySelectorAll("button, a[href], [tabindex='0']")).filter(element => !element.disabled && !element.hidden);
    const first = focusable[0], last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
    else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
  }
});
// Only dismiss a genuine backdrop press, not a drag from inside the story.
let backdropPress = false;
dialog.addEventListener("pointerdown", event => { backdropPress = event.target === dialog; });
dialog.addEventListener("click", event => {
  if (event.target === dialog && backdropPress) {
    const rect = dialog.getBoundingClientRect();
    if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) closeAchievement();
  }
  backdropPress = false;
});

evidenceButton.addEventListener("click", () => {
  const expanded = evidenceButton.getAttribute("aria-expanded") === "true";
  evidenceButton.setAttribute("aria-expanded", String(!expanded));
  evidenceContent.hidden = expanded;
});

believeButton.addEventListener("click", () => {
  if (!currentAchievement) return;
  const id = currentAchievement.id;
  if (confirmedIds.has(id)) {
    confirmedIds.delete(id);
    showToast("Belief withdrawn. My imaginary lawyers have been notified.");
  } else {
    confirmedIds.add(id);
    celebrate();
    showToast(`You believed ${confirmedIds.size} of 6 legends. Excellent judgment.`);
  }
  savePreferences();
  syncBelieveButton();
  renderCards();
});

document.getElementById("share-button").addEventListener("click", async () => {
  if (!currentAchievement) return;
  const url = new URL(location.href);
  url.hash = `legend/${currentAchievement.id}`;
  const text = location.protocol === "file:"
    ? `Egor Shevchenko: ${currentAchievement.title} — A fictional tale from Desalot’s very modest archive.`
    : url.href;
  const copied = await copyText(text);
  if (copied) showToast(location.protocol === "file:" ? "Legend copied. Publish the site to share direct links." : "Legend link copied. Spread the highly questionable word.");
  else window.prompt("Copy this legend to share:", text);
});

function openFromHash() {
  const match = location.hash.match(/^#legend\/([a-z0-9-]+)$/);
  if (match) openAchievement(match[1], false);
  else if (dialog.hasAttribute("open")) closeAchievement();
}
window.addEventListener("hashchange", openFromHash);
document.getElementById("current-year").textContent = new Date().getFullYear();
renderCards();
openFromHash();
